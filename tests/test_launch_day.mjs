import assert from "node:assert/strict";
import * as L from "../apps/games/launch-day/core.mjs";
const a={aluno:"demo-a",nome:"Player A"},b={aluno:"demo-b",nome:"Player B"};
assert.equal(L.validarCriacao({equipes:["A"]}),"at least 2 teams");
let s=L.criar({equipes:["Alpha","Beta"]},2027);
assert.deepEqual(s.eventos,L.criar({equipes:["Alpha","Beta"]},2027).eventos);
s=L.entrar(s,a);s=L.entrar(s,b);
s=L.jogador(s,a,{tipo:"team",equipe:"t1"});
s=L.jogador(s,b,{tipo:"team",equipe:"t2"});
s=L.jogador(s,a,{tipo:"business",negocio:"Demo Food",tipoNegocio:"food"});
s=L.host(s,{tipo:"start"});
assert.equal(s.fase,"decide");
assert.throws(()=>L.jogador(s,a,{tipo:"business",negocio:"Other"}));
s=L.jogador(s,a,{tipo:"choose",opcoes:["app"]});
assert.equal(L.ver(s,"player",a).minha.rascunho[0],"app");
assert(!JSON.stringify(L.ver(s,"host").equipes).includes('"app"'));
assert(!JSON.stringify(L.ver(s,"player",b).equipes).includes('"app"'));
s=L.host(s,{tipo:"reveal"});
assert.deepEqual(s.equipes[1].historico[0].escolhas,["physical"]);
s=L.host(s,{tipo:"next"});
assert.throws(()=>L.jogador(s,a,{tipo:"choose",opcoes:["pix"]}));
s=L.jogador(s,a,{tipo:"choose",opcoes:["pix","stock"]});
s=L.host(s,{tipo:"reveal"});
assert(s.equipes[0].historico[1].linhas.some(l=>l.tipo==="custo"));
for(let i=2;i<L.RODADAS.length;i++){s=L.host(s,{tipo:"next"});s=L.host(s,{tipo:"reveal"});}
s=L.host(s,{tipo:"next"});
assert.equal(s.fase,"final");
assert(s.equipes.every(t=>t.historico.length===5&&Object.values(t.m).every(v=>Number.isFinite(v)&&v>=0&&v<=10)));
assert.throws(()=>L.jogador(s,a,{tipo:"choose",opcoes:["savings"]}));
assert.equal(L.ver(s,"host").rodadas.length,5);
console.log("PASS: Launch Day recovered core, five rounds and secrecy");
